#!/usr/bin/env python3
"""Generate ABI bindings from our small, intentionally plain C header (no clang dependency)."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent.parent
header=(root/'native/include/lib_onnx.h').read_text()
handles=['Runtime','Session','Tensor','DiagnosticReport','Task']
native={'int32_t':'ffi.Int32','uint32_t':'ffi.Uint32','int64_t':'ffi.Int64','size_t':'ffi.Size','void':'ffi.Void','char':'ffi.Char'}
dart={'int32_t':'int','uint32_t':'int','int64_t':'int','size_t':'int','void':'void'}
for h in handles:
    native['LibOnnx'+h+'Handle']='ffi.Pointer<LibOnnx'+h+'>'
    dart['LibOnnx'+h+'Handle']=native['LibOnnx'+h+'Handle']
def types(s):
    s=re.sub(r'\bconst\b','',s).strip()
    stars=s.count('*');base=s.replace('*','').strip()
    n=native[base];d=dart.get(base,n)
    for _ in range(stars): n='ffi.Pointer<'+n+'>';d=n
    return n,d
out=['// GENERATED by tools/generate_bindings.py from native/include/lib_onnx.h.\n',"import 'dart:ffi' as ffi;", "import 'c_structures.dart';", "import 'native_library.dart';",'class LibOnnxBindings {','final ffi.DynamicLibrary library;','LibOnnxBindings(this.library);']
for ret,name,args in re.findall(r'LIB_ONNX_EXPORT\s+([\w\s*]+?)\b(lib_onnx_\w+)\((.*?)\);',header,re.S):
    rn,rd=types(ret)
    at=[]
    if args.strip()!='void' and args.strip():
        for arg in args.split(','):
            arg=re.sub(r'/\*.*?\*/','',arg,flags=re.S).strip()
            typ=re.sub(r'\b\w+$','',arg).strip()
            at.append(types(typ))
    method=re.sub(r'_([a-z])',lambda m:m[1].upper(),name.removeprefix('lib_onnx_'))
    nt=f'{rn} Function('+','.join(a[0] for a in at)+')'
    dt=f'{rd} Function('+','.join(a[1] for a in at)+')'
    out.append(f"late final {dt} {method} = library.lookupFunction<{nt}, {dt}>('{name}');")
out.extend(['static LibOnnxBindings? _instance;', 'static LibOnnxBindings get instance => _instance ??= LibOnnxBindings(NativeLibrary.load());', 'static void init({String? libraryPath}) { _instance = LibOnnxBindings(NativeLibrary.load(overridePath: libraryPath)); }','}'])
(root/'lib/src/ffi/bindings.dart').write_text('\n'.join(out)+'\n')
(root/'lib/src/ffi/c_structures.dart').write_text("// GENERATED by tools/generate_bindings.py.\nimport 'dart:ffi' as ffi;\n"+'\n'.join('final class LibOnnx'+h+' extends ffi.Opaque {}' for h in handles)+'\n')
